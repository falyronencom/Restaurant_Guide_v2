/// Третий аргумент `window.open` для ссылок из панели.
///
/// `noopener` — у новой вкладки нет `window.opener`: открытая страница не
/// может подменить вкладку панели (например, поддельным входом).
/// `noreferrer` — адрес панели не уходит открытой странице. Сегодня все такие
/// адреса задаёт сервер (медиа нашего облака, Яндекс Карты), но вкладка
/// модератора не должна зависеть от того, что окажется по ссылке
/// (сверка меток панели 29.10, «Вне меток» п. 2).
///
/// Отдельным файлом без `dart:js_interop`: так строку видит и тест на Dart VM.
const String kNewTabFeatures = 'noopener,noreferrer';
