// Оценка и цена места — одними словами в списке, в карточке заведения, в
// превью на карте и в подсказках умного поиска.
//
// Раньше каждый экран писал их по-своему: список — «0,0», карточка — «0.0»,
// карта — «4.8»; список показывал цену, как её хранит сервер («$»), а
// карточка переводила её через таблицу старых слов («budget», «moderate»),
// которых сервер не присылает, и на любое настоящее значение отвечала «$$»
// (находки 18.10.2026 на телефоне Координатора).

/// Средняя оценка места для показа: «4,5» — один знак после русской запятой.
///
/// `null` — оценок нет. Сервер отдаёт у места без отзывов среднюю 0, а не
/// пустое поле; зелёный значок «0,0» читался как «ноль из пяти». Оценки бывают
/// от 1 до 5, поэтому средняя не больше нуля — это «оценок нет», а не оценка.
/// Сайт по тому же правилу значок не рисует (`review_count > 0`).
String? ratingLabel(double? rating) {
  if (rating == null || !rating.isFinite || rating <= 0) return null;
  return rating.toStringAsFixed(1).replaceAll('.', ',');
}

/// Цена места так, как её хранит сервер: «$», «$$», «$$$».
///
/// `null` — цены нет: поле пустое или не пришло. Значение не переводится и не
/// подменяется — список и карточка обязаны показывать одно и то же.
String? priceLabel(String? priceRange) {
  final value = priceRange?.trim();
  if (value == null || value.isEmpty) return null;
  return value;
}
