import 'dart:math' as math;

// Оценка, цена и расстояние до места — одними словами в списке, в карточке
// заведения, в превью на карте и в подсказках умного поиска.
//
// Раньше каждый экран писал их по-своему: список — «0,0», карточка — «0.0»,
// карта — «4.8»; список показывал цену, как её хранит сервер («$»), а
// карточка переводила её через таблицу старых слов («budget», «moderate»),
// которых сервер не присылает, и на любое настоящее значение отвечала «$$»
// (находки 18.10.2026 на телефоне Координатора).

/// Средняя оценка места для показа: «4,5» — один знак после русской запятой.
///
/// `null` — оценок нет. Сервер отдаёт у места без отзывов среднюю 0, а не
/// пустое поле; зелёный значок «0,0» читался как «ноль из пяти». Оценки бывают
/// от 1 до 5, поэтому средняя не больше нуля — это «оценок нет», а не оценка.
/// Сайт по тому же правилу значок не рисует (`review_count > 0`).
String? ratingLabel(double? rating) {
  if (rating == null || !rating.isFinite || rating <= 0) return null;
  return rating.toStringAsFixed(1).replaceAll('.', ',');
}

/// Цена места значками, как её хранит сервер: «$», «$$», «$$$».
///
/// `null` — цены нет: поле пустое или не пришло. Значение не переводится и не
/// подменяется — список и карточка обязаны показывать одно и то же. Значки —
/// там, где места на слова нет: под квадратом оценки в списке и в карточке
/// (так же сайт пишет цену в своём списке). Словами — [priceDescription].
String? priceLabel(String? priceRange) {
  final value = priceRange?.trim();
  if (value == null || value.isEmpty) return null;
  return value;
}

/// Средний чек словами для каждого значения сервера (`VALID_PRICE_RANGES`,
/// `backend/src/validators/establishmentValidation.js`) — те же слова, что у
/// сайта (`PRICE_DESCRIPTION`, `web/src/components/establishment/InfoCard.tsx`)
/// и панели (`kPriceRangeLabels`). Равенство набору сервера и словам сайта
/// стережёт `test/utils/price_description_test.dart`.
///
/// До 29.10.2026 приложение писало только значки «$$», сайт — «до 50 руб»
/// (находка нитки панели, 25.10).
const Map<String, String> priceRangeDescriptions = <String, String>{
  r'$': 'до 20 руб',
  r'$$': 'до 50 руб',
  r'$$$': 'более 50 руб',
};

/// Средний чек словами: «до 50 руб». `null` — цены нет или значение
/// незнакомое (такого сервер не принимает; значки «$$$$» словами не
/// назвать, а строка «Средний чек: $$$$» обещала бы то, чего нет).
String? priceDescription(String? priceRange) =>
    priceRangeDescriptions[priceRange?.trim()];

/// Расстояние до места для показа: до километра — метры с точностью до
/// десяти («200 м», не меньше «10 м»), дальше — километры с одним знаком
/// после русской запятой («2,0 км»). [km] — в километрах, как его отдают
/// сервер и `LocationService`.
///
/// Одно правило на всех экранах. Прежде список писал «0,2 км от вас»
/// (всегда километры), карточка того же места — «200 м от вас», а дальше
/// «2.0 км от вас» (с точкой), подсказки умного поиска — «1.2 км» (Н1,
/// 19.10.2026). Прогулка «Пешком» в «Избранном» уже писала так —
/// `walkDistanceLabel` теперь берёт это правило отсюда.
String distanceLabel(double km) => distanceLabelMeters(km * 1000);

/// То же правило, что [distanceLabel], для расстояния в метрах.
///
/// Не число («NaN», «Infinity» разбираются из строки сервера) — «—»: округление
/// такого значения бросает исключение и роняло бы экран.
String distanceLabelMeters(double meters) {
  if (!meters.isFinite) return '—';
  final tens = (meters / 10).round() * 10;
  if (tens < 1000) return '${math.max(tens, 10)} м';
  return '${(meters / 1000).toStringAsFixed(1).replaceAll('.', ',')} км';
}
