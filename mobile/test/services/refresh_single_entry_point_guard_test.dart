import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

/// Сторож единственной точки предъявления refresh-токена.
///
/// **Что стережётся.** Коммиты `97eb247` и `1b146bf` (13.09.2026) установили
/// границу: **не более двух предъявлений refresh-токена за цикл обновления**,
/// оба отправленные не позже таймаута приёма (30 с) от ротации. Граница не
/// декоративна — на бэкенде предъявление погашенного токена вне льготного
/// окна (`REFRESH_REUSE_GRACE_SECONDS`, умолчание 60 с) означает 403
/// `TOKEN_REUSE_DETECTED` и отзыв ВСЕХ сессий пользователя.
///
/// Держится граница на одном допущении: единственный код, который стучится в
/// `/auth/refresh`, — `_doTokenRefresh` в `lib/services/api_client.dart`, и
/// зовут его только из-под замка `_refreshCompleter`. Счётчики предъявлений в
/// `api_client_refresh_transient_test.dart` меряют именно этот путь.
///
/// **Почему счётчиков мало.** Они стерегут поведение существующего пути и
/// слепы ко второму. Второй путь — не гипотеза: `AuthService.refreshToken()`
/// POST-ил `/api/v1/auth/refresh` напрямую, мимо замка, и нёс собственный
/// `catch -> clearAuthData()`. Вызывающих у него не было, поэтому он не красил
/// ничего и прожил незамеченным до ревью 13.09; удалён `4064c00`. Один вызов
/// из нового кода отменил бы границу молча — ни `flutter analyze`, ни набор
/// тестов такой вызов не ловят, потому что ни один страж не считает
/// предъявления ЗА ПРЕДЕЛАМИ перехватчика.
///
/// Вопрос брифа аудита к любому сквозному сторожу: *как его выключить, не
/// изменив вывод прогона?* Здесь ответ честный и неполный: **собрать путь по
/// частям** (`'/api/v1/auth/' + 'refresh'`) или сходить на него по адресу,
/// записанному иначе. Сторож ловит очевидную форму — ту, которой второй путь
/// и был написан, — а не вооружённый обход. Это растяжка, а не песочница.
void main() {
  /// Строковый литерал, внутри которого лежит путь обновления, в любых
  /// кавычках. Ищется именно ЛИТЕРАЛ, а не любое упоминание: doc-комментарии
  /// поминают `/auth/refresh` в обратных кавычках, и по «любому упоминанию»
  /// сторож краснел бы на переписанном комментарии — ложная тревога быстро
  /// приучает править сторожа вместо кода.
  const literal = r"""['"][^'"]*auth/refresh[^'"]*['"]""";

  /// Вызов запроса, первым аргументом которого стоит путь обновления —
  /// литералом или через константу `_refreshPath`.
  final requestCall = RegExp(
    r'\.(?:post|get|put|patch|delete|head|request)\s*(?:<[^<>]*>\s*)?\(\s*'
    '(?:_refreshPath|$literal)',
  );

  final refreshLiteral = RegExp(literal);

  /// Файлы, которым путь обновления знать положено, и почему.
  ///
  /// Список намеренно объясняет каждую строку: безымянное исключение
  /// позволило бы будущему исполнителю вписать сюда свой файл, лишь бы
  /// прогон позеленел, — ровно то, от чего сторож и поставлен.
  const allowed = <String, String>{
    'lib/services/api_client.dart':
        'владелец замка _refreshCompleter: здесь и только здесь живут '
            'константа _refreshPath, предикат _isRefreshRequest и сам '
            '_doTokenRefresh, чьи предъявления сосчитаны в '
            'api_client_refresh_transient_test.dart',
  };

  final apiClient = File('lib/services/api_client.dart');

  group('Единственная точка предъявления refresh-токена', () {
    test('в api_client.dart ровно один запрос на путь обновления', () {
      expect(apiClient.existsSync(), isTrue,
          reason: 'не найден ${apiClient.path} — файл переехал, и сторож '
              'стережёт пустоту');

      final source = apiClient.readAsStringSync();
      final calls = requestCall.allMatches(source).toList();

      expect(
        calls.length,
        1,
        reason: 'запросов на путь обновления в api_client.dart: '
            '${calls.length}, а должен быть ровно один — тот, что в '
            '_doTokenRefresh под замком _refreshCompleter. Найдено: '
            '${calls.map((m) => m.group(0)).toList()}. Второй запрос в этом '
            'же файле удваивает предъявления погашенного токена: вне '
            'льготного окна бэкенда это 403 TOKEN_REUSE_DETECTED и отзыв '
            'всех сессий пользователя',
      );
    });

    test('ни один другой файл lib/ не знает пути обновления', () {
      final sources = Directory('lib')
          .listSync(recursive: true)
          .whereType<File>()
          .where((f) => f.path.endsWith('.dart'))
          .toList();

      expect(sources.length, greaterThan(50),
          reason: 'обход lib/ нашёл всего ${sources.length} файлов — сменился '
              'рабочий каталог прогона или раскладка проекта, и сторож '
              'перестал что-либо стеречь');

      final offenders = <String>[];
      for (final file in sources) {
        // Пути в отчёте — в одной, посикс-подобной форме: на Windows
        // listSync отдаёт '\', и сверка с ключами allowed промахивалась бы.
        final path = file.path.replaceAll(r'\', '/');
        if (allowed.containsKey(path)) continue;
        if (refreshLiteral.hasMatch(file.readAsStringSync())) {
          offenders.add(path);
        }
      }

      expect(
        offenders,
        isEmpty,
        reason: 'путь обновления упомянут вне ${allowed.keys.join(', ')}: '
            '$offenders. Так и выглядел удалённый AuthService.refreshToken() '
            '— второй путь обновления мимо замка. Если файл обязан знать '
            'этот путь, вписать его в allowed С ПРИЧИНОЙ и объяснить, почему '
            'он не ломает границу двух предъявлений',
      );
    });

    test('сам поиск находит то, что обязан находить', () {
      // Обход lib/ выше зеленеет ДВУМЯ способами: нарушителей нет — и поиск
      // сломан. Второй способ беззвучен, поэтому проверяется здесь: регэксп
      // предъявляется коду, в котором путь обновления заведомо есть.
      //
      // Парного утверждения про `requestCall` тут нет намеренно: сломанный
      // поиск вызова валит счёт в первом стороже (0 вместо 1), и дубль лишь
      // прятал бы, кто из двоих на самом деле необходим.
      expect(refreshLiteral.hasMatch(apiClient.readAsStringSync()), isTrue,
          reason: 'поиск литерала не нашёл путь обновления в '
              '${apiClient.path} — регэксп разошёлся с формой записи пути, и '
              'обход lib/ выше ничего не стережёт');

      // Каждый ключ allowed обязан существовать: мёртвая строка в списке
      // исключений означала бы, что сторож отчитывается о файле, которого нет.
      for (final path in allowed.keys) {
        expect(File(path).existsSync(), isTrue,
            reason: 'в allowed числится несуществующий $path');
      }
    });
  });
}
