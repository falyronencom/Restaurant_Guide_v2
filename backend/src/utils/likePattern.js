/**
 * Шаблон LIKE / ILIKE, который совпадает с текстом буквально.
 *
 * «%» и «_», набранные человеком, — символы, а не подстановки: без этого
 * поиск «100%» находит «1000 грамм», а одинокий «%» возвращает всю очередь,
 * хотя поле на экране обещает её фильтровать. Обратная косая экранируется
 * тоже — она и есть знак экранирования. Пара к шаблону в SQL обязательна:
 * `ILIKE $n ESCAPE '\'` (в строке JS — `ESCAPE '\\'`).
 *
 * Одна функция на весь сервер. Прежде было четыре копии — поиск отзывов
 * (adminReviewModel), очередь позиций меню (menuItemModel), поиск заведений
 * (establishmentModel) и шаблоны почты оператора (scripts/lib/serviceAccounts.js);
 * поведение то же: две копии приводили значение к строке (String), две нет,
 * но к ним приходят только строки — разницы ни на одном вызове нет.
 */

/**
 * @param {string} value - Текст, набранный человеком
 * @returns {string} Тот же текст с экранированными «\», «%» и «_»
 */
export const escapeLike = (value) => String(value).replace(/[\\%_]/g, (char) => `\\${char}`);

/**
 * Шаблон «содержит»: `%текст%`, текст — буквально.
 *
 * @param {string} value
 * @returns {string}
 */
export const likeContains = (value) => `%${escapeLike(value)}%`;
