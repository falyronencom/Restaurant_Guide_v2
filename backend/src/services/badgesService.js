/**
 * Badges Service — счётчики очередей для рейла админки и панели «Требует
 * внимания» на дашборде.
 *
 * Зачем отдельный эндпоинт. Рейл живёт в шелле и рисуется на каждом экране, а
 * счётчики в нём нужны везде. Альтернатива — дозапрашивать три списка с
 * per_page=1 ради meta.total — даёт три лишних round-trip на каждый переход
 * между разделами. Здесь это одна выборка, да ещё и под кэшем.
 *
 * Кэш внутрипроцессный, не Redis. В проекте Redis обслуживает счётчики
 * rate-limit, приёма кэширования ответов нет, а заводить его ради четырёх
 * чисел — лишний режим отказа: при недоступном Redis эндпоинт обязан был бы
 * деградировать, и это пришлось бы отдельно продумывать и тестировать.
 * Данные не критичны к свежести: показать очередь 30-секундной давности
 * безопасно, счётчик всё равно меняется реже, чем модератор переходит между
 * экранами.
 */

import * as BadgesModel from '../models/badgesModel.js';
import * as QualityHealthModel from '../models/qualityHealthModel.js';
import logger from '../utils/logger.js';

/** Время жизни кэша. Нижняя граница диапазона 30–60 с из брифа. */
export const CACHE_TTL_MS = 30_000;

let cache = null;

/**
 * Сбрасывает кэш.
 *
 * Вызывается со стороны ЗАПИСИ: любое действие модератора, меняющее размер
 * очереди (одобрение, отказ, приостановка, скрытие позиции меню, снятие
 * флага), обязано сбросить кэш. Иначе бейдж в рейле до полминуты показывал бы
 * число, которое сам же модератор только что изменил, — и это читалось бы как
 * «действие не сработало».
 */
export const invalidateCache = () => {
  cache = null;
};

/**
 * Счётчики очередей.
 *
 * Форма ответа:
 * {
 *   establishments_pending: int,
 *   establishments_suspended: int,
 *   menu_flags: int,
 *   menu_flags_aged_over_7d: int,
 *   generated_at: ISO-строка
 * }
 *
 * Намеренно НЕ содержит «сигналов здоровья данных» и «отзывов на разбор» — и
 * НЕ будет содержать (решено 27.08.2026, этап 7 редизайна admin-web).
 *
 * Правило для сигналов здоровья теперь есть: сигнал = красная карточка экрана
 * «Здоровье данных», то есть проверка со счётчиком больше нуля. Но адрес другой.
 * Получить это число нельзя, не выполнив все одиннадцать проверок, а три из них
 * вытягивают все активные заведения и перебирают их в JS. Этот эндпоинт зовётся
 * при монтировании шелла и после КАЖДОГО действия модератора — то есть одобрение
 * заведения пересчитывало бы достижимость всего каталога в sitemap. Панель
 * «Требует внимания» на дашборде берёт эту величину напрямую из
 * `/admin/quality/health` (там свой кэш и своя кнопка обновления), а бейджа в
 * рейле у «Здоровья данных» нет намеренно: экран лежит в одном клике и считает
 * то же самое честно.
 *
 * «Отзывов на разбор» остаётся без определения: механизма жалоб в системе нет
 * (ни таблицы, ни колонки, ни эндпоинта), а косвенная метрика вроде «низкая
 * оценка без ответа партнёра» ставила бы перед админом очередь честных единиц.
 *
 * @param {{ force?: boolean }} [options] force обходит кэш.
 */
export const getBadges = async ({ force = false } = {}) => {
  const now = Date.now();

  if (!force && cache && now - cache.at < CACHE_TTL_MS) {
    return cache.value;
  }

  try {
    const [queues, flags] = await Promise.all([
      BadgesModel.getEstablishmentQueueCounts(),
      QualityHealthModel.getHangingFlags(),
    ]);

    const value = {
      establishments_pending: queues.pending,
      establishments_suspended: queues.suspended,
      menu_flags: flags.hanging_count,
      menu_flags_aged_over_7d: flags.aged_over_7d,
      generated_at: new Date(now).toISOString(),
    };

    cache = { at: now, value };
    return value;
  } catch (error) {
    logger.error('Error building admin badges', { error: error.message });
    throw error;
  }
};
